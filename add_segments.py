def main():
    d = json.load(open(PATH, encoding='utf-8'))
    case = d['cases']['northlake'][0]
    for i, node in enumerate(case['nodes']):
        segs = SEGS[i]
        node['segments'] = [
            {"speaker": s, "voice_hint": h, "emotion": e, "text": t}
            for (s, h, e, t) in segs
        ]
    with open(PATH, 'w', encoding='utf-8') as f:
        json.dump(d, f, ensure_ascii=False, separators=(',', ':'))
    # 同步 file:// 内联库
    with open('cases_data.js', 'w', encoding='utf-8') as f:
        f.write('/* 试玩版内联案件库（file:// 直开时 fetch 被浏览器禁用，走此数据） */\n')
        f.write('window.CASES_DATA = ')
        f.write(json.dumps(d, ensure_ascii=False, separators=(',', ':')))
        f.write(';\n')
    # 校验：分段拼接覆盖率（运行时要求 >= 50% 才不退化为整段旁白）
    for i, node in enumerate(case['nodes']):
        seg_len = sum(len(s['text']) for s in node['segments'])
        scene_len = len(node['scene'])
        ratio = seg_len / scene_len
        assert ratio >= 0.5, f'node {i} coverage {ratio:.0%} < 50%'
        print(f'node {i}: {len(node["segments"])} segs, coverage {ratio:.0%}')

if __name__ == '__main__':
    main()
